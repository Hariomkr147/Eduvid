"""AI4Bharat IndicF5 (MIT; gated: needs HF_TOKEN). Needs a reference clip + its exact transcript per voice.

Voices are reference clips in /models/refs/indicf5/<id>.wav with the transcript in <id>.txt.
Terms of use: only clone voices you have explicit permission for. Our references are synthetic
(generated by our own Apache-licensed Kokoro Hindi voices), not recordings of real people.
"""
import os
from pathlib import Path

from eduvid_common.tts_server import Backend, make_app

REPO = os.environ.get("INDICF5_REPO", "ai4bharat/IndicF5")
REFS = Path(os.environ.get("INDICF5_REFS", "/models/refs/indicf5"))


class IndicF5Backend(Backend):
    name = "indicf5"

    def load(self) -> None:
        from transformers import AutoModel

        self.model = AutoModel.from_pretrained(REPO, trust_remote_code=True, token=os.environ.get("HF_TOKEN") or None)
        try:
            self.model = self.model.to("cuda:0")
        except Exception:  # noqa: BLE001 — remote code may manage its own device
            pass
        self.refs = {}
        for wav in sorted(REFS.glob("*.wav")) if REFS.exists() else []:
            txt = wav.with_suffix(".txt")
            if txt.exists():
                self.refs[wav.stem] = (str(wav), txt.read_text().strip())

    def voices(self) -> list[dict]:
        return [{"id": k, "language": "hi", "description": f"reference clip {Path(w).name}"}
                for k, (w, _) in self.refs.items()]

    def synthesize(self, text, voice, language, instruct, speed, seed):
        import numpy as np

        wav, ref_text = self.refs[voice]
        audio = self.model(text, ref_audio_path=wav, ref_text=ref_text)
        audio = np.asarray(audio)
        if audio.dtype == np.int16:
            audio = audio.astype(np.float32) / 32768.0
        return audio, 24000


app = make_app(IndicF5Backend())
